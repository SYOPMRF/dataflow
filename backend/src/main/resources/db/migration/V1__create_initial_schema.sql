
CREATE TABLE users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL,
    email VARCHAR(255) NOT NULL,
    password_hash VARCHAR(255) NOT NULL,
    updated_at TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL,
    CONSTRAINT uk_users_email UNIQUE (email)
);

CREATE TABLE files (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL,
    file_size BIGINT NOT NULL,
    file_type VARCHAR(255) NOT NULL,
    original_name VARCHAR(255) NOT NULL,
    processed_at TIMESTAMP(6) WITHOUT TIME ZONE,
    status VARCHAR(255) NOT NULL,
    stored_name VARCHAR(255) NOT NULL,
    user_id BIGINT NOT NULL,
    CONSTRAINT uk_files_stored_name UNIQUE (stored_name),
    CONSTRAINT fk_files_user FOREIGN KEY (user_id) REFERENCES users(id),
    CONSTRAINT chk_files_status CHECK (
        status IN ('UPLOADED', 'PROCESSING', 'COMPLETED', 'FAILED')
    )
);

CREATE TABLE analysis_results (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    column_count INTEGER NOT NULL,
    created_at TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL,
    duplicate_count INTEGER NOT NULL,
    missing_count INTEGER NOT NULL,
    row_count INTEGER NOT NULL,
    file_id BIGINT NOT NULL,
    CONSTRAINT uk_analysis_results_file UNIQUE (file_id),
    CONSTRAINT fk_analysis_results_file FOREIGN KEY (file_id) REFERENCES files(id)
);

CREATE TABLE data_quality_issues (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    column_name VARCHAR(255) NOT NULL,
    issue_type VARCHAR(255) NOT NULL,
    message VARCHAR(255) NOT NULL,
    severity VARCHAR(255) NOT NULL,
    file_id BIGINT NOT NULL,
    CONSTRAINT fk_data_quality_issues_file FOREIGN KEY (file_id) REFERENCES files(id)
);

CREATE TABLE file_columns (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    completely_empty BOOLEAN NOT NULL,
    data_type VARCHAR(255) NOT NULL,
    duplicate_count INTEGER NOT NULL,
    duplicated_unique_count INTEGER NOT NULL,
    max_value VARCHAR(255),
    mean_value DOUBLE PRECISION,
    median_value DOUBLE PRECISION,
    min_value VARCHAR(255),
    missing_percentage DOUBLE PRECISION NOT NULL,
    name VARCHAR(255) NOT NULL,
    negative_count INTEGER NOT NULL,
    null_count INTEGER NOT NULL,
    std_deviation DOUBLE PRECISION,
    unique_count INTEGER NOT NULL,
    unique_percentage DOUBLE PRECISION NOT NULL,
    zero_count INTEGER NOT NULL,
    file_id BIGINT NOT NULL,
    CONSTRAINT fk_file_columns_file FOREIGN KEY (file_id) REFERENCES files(id)
);